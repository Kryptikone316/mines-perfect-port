#!/usr/bin/env python3
"""Bakes DejaVu Sans glyph atlases (Latin-1, 8-bit alpha) into sdl/font_data.h.  Needs Pillow:  ~/venvs/pydev/bin/python tools/bake_font.py
DejaVu fonts: Bitstream Vera licence + public-domain changes, see licenses/DejaVu-fonts-LICENSE.txt (redistribution allowed)."""
import sys
from PIL import ImageFont

REG = '/usr/share/fonts/dejavu/DejaVuSans.ttf'
BOLD = '/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf'
FONTS = [('ui_small', REG, 13), ('ui', REG, 17), ('ui_bold', BOLD, 17), ('ui_big', BOLD, 26)]
out = ['/* generated by tools/bake_font.py - do not edit */', '#include <stdint.h>',
       'struct BakedGlyph { uint8_t w, h; int8_t xoff, yoff; uint8_t adv; uint32_t off; };',
       'struct BakedFont  { int height, ascent; const BakedGlyph* glyphs; const uint8_t* alpha; };']
for name, path, px in FONTS:
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    glyphs, blob = [], bytearray()
    for c in range(32, 256):
        ch = chr(c)
        if 127 <= c < 160:
            glyphs.append((0, 0, 0, 0, 0, len(blob))); continue
        adv = int(round(f.getlength(ch)))
        l, t, r, b = f.getbbox(ch, anchor='ls')           # relative to baseline origin
        w, h = max(0, r - l), max(0, b - t)
        off = len(blob)
        if w and h and ch != ' ':
            from PIL import Image, ImageDraw
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor='ls')
            blob += im.tobytes()
        else:
            w = h = 0
        glyphs.append((w, h, l, t + asc, adv, off))      # yoff relative to the top of the line box
    out.append('static const uint8_t %s_alpha[] = {%s};' % (name, ','.join(map(str, blob)) if blob else '0'))
    out.append('static const BakedGlyph %s_glyphs[224] = {%s};' % (name, ','.join('{%d,%d,%d,%d,%d,%d}' % g for g in glyphs)))
    out.append('static const BakedFont bf_%s = {%d,%d,%s_glyphs,%s_alpha};' % (name, asc + desc, asc, name, name))
open('sdl/font_data.h', 'w').write('\n'.join(out) + '\n')
print('ok')
